// Cucumber-Ruby defines every step keyword of every Gherkin dialect as a DSL method. The table in
// src/ruby/step_keywords.rs is derived from the Gherkin dialect data pinned by Cargo.lock; this
// check fails when a dependency update changes that data. `--write` regenerates the table.
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

const target = "src/ruby/step_keywords.rs";
const metadata = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));
const gherkin = metadata.packages.find((item) => item.name === "gherkin");
if (!gherkin) throw new Error("gherkin package not found in cargo metadata");
const dialects = JSON.parse(await readFile(join(dirname(gherkin.manifest_path), "src/languages.json"), "utf8"));

// Keywords with spaces, apostrophes or other symbols, apart from a trailing `!` or `?`, can only be
// invoked through `send`, which the adapter already treats as dynamic dispatch.
const callable = /^[\p{L}_][\p{L}\p{M}\p{N}_]*[!?]?$/u;
const keywords = new Set();
for (const dialect of Object.values(dialects)) {
  for (const kind of ["given", "when", "then", "and", "but"]) {
    for (const keyword of dialect[kind]) {
      const name = keyword.trim();
      if (callable.test(name)) keywords.add(name);
    }
  }
}
const sorted = [...keywords].sort((left, right) => Buffer.compare(Buffer.from(left), Buffer.from(right)));
const rendered = `// Generated by scripts/check/check-ruby-step-keywords.mjs --write from gherkin ${gherkin.version}
// dialect data. Do not edit by hand.

/// Step keywords of every Gherkin dialect that Ruby can call as a bare method, in byte order.
pub(super) const STEP_KEYWORDS: &[&str] = &[
${sorted.map((name) => `    ${JSON.stringify(name)},`).join("\n")}
];
`;
if (process.argv.includes("--write")) {
  await writeFile(target, rendered);
  console.log(`${target}: ${sorted.length} keywords`);
} else {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== rendered) {
    console.error(`${target} is stale; run node scripts/check/check-ruby-step-keywords.mjs --write`);
    process.exitCode = 1;
  } else {
    console.log(`Ruby step keywords match gherkin ${gherkin.version}: ${sorted.length} keywords`);
  }
}
