import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { decodeSarifUri, sarifDisplayPath } from "./sarif-uri.mjs";

/** Percent-encodes every byte outside RFC 3986 unreserved, as the SARIF reporter does. */
function encode(bytes) {
  return [...bytes].map((byte) => (/[A-Za-z0-9._~-]/.test(String.fromCharCode(byte))
    ? String.fromCharCode(byte)
    : `%${byte.toString(16).toUpperCase().padStart(2, "0")}`)).join("");
}

/** Named cases: reserved characters, a literal `%41` name, multibyte text and invalid UTF-8. */
test("decodeSarifUri decodes reserved, multibyte and invalid bytes", () => {
  assert.equal(decodeSarifUri("dir%20%231/sub%2541/a%3Fb%20c.ts"), "dir #1/sub%41/a?b c.ts");
  assert.equal(decodeSarifUri("a%E2%80%A6"), "a…");
  assert.equal(decodeSarifUri("a%FFb.ts"), "a�b.ts");
  assert.equal(decodeSarifUri("a%C3"), "a�");
  // A leading U+FEFF is part of the file name, not a byte-order mark.
  assert.equal(decodeSarifUri("%EF%BB%BFsteps.ts"), "\uFEFFsteps.ts");
});

/** Seeded bytes: decoding the encoded form equals Node's own lossy UTF-8 reading of the bytes. */
test("decodeSarifUri matches Buffer UTF-8 decoding for generated bytes", () => {
  let seed = 42;
  /** Linear congruential step: deterministic bytes without a dependency. */
  const next = () => (seed = (seed * 1103515245 + 12345) % 2 ** 31);
  for (let run = 0; run < 256; run += 1) {
    // Every eighth case starts with EF BB BF, which a default TextDecoder would strip.
    const lead = run % 8 === 0 ? [0xef, 0xbb, 0xbf] : [];
    const bytes = Uint8Array.from([...lead, ...Array.from({ length: next() % 24 }, () => next() % 256)]);
    assert.equal(decodeSarifUri(encode(bytes)), Buffer.from(bytes).toString("utf8"), encode(bytes));
  }
});

/** Display projection matches the JSON reporter: invisible characters escaped and `\\` read as `/`. */
test("sarifDisplayPath applies the JSON display-path rules", () => {
  assert.equal(sarifDisplayPath("a%E2%80%AEb.ts"), "a\\u{202e}b.ts");
  assert.equal(sarifDisplayPath("%EF%BB%BFsteps.ts"), "\\u{feff}steps.ts");
  assert.equal(sarifDisplayPath("x%5Cz.ts"), "x/z.ts");
  assert.equal(sarifDisplayPath("a%07%09%0A%0Db.ts"), "a\t\n\rb.ts");
  assert.equal(sarifDisplayPath("%F3%A0%80%81tag%C2%ADsoft.ts"), "\\u{e0001}tag\\u{ad}soft.ts");
  assert.equal(sarifDisplayPath("dir%20%231/a%FFb.ts"), "dir #1/a\uFFFDb.ts");
});

/** Shared cases also checked against both Rust reporters by `shared_display_cases_match_both_reporters`. */
test("sarifDisplayPath matches the shared reporter display cases", () => {
  const { cases } = JSON.parse(readFileSync(
    new URL("../../../fixtures/reporters/sarif-display-paths.json", import.meta.url), "utf8"));
  assert.ok(cases.some((entry) => entry.unixOnly) && cases.some((entry) => !entry.unixOnly));
  for (const { uri, display } of cases) assert.equal(sarifDisplayPath(uri), display, uri);
});

/** Bounds display expansion while raw URI decoding preserves the entire value. */
test("sarifDisplayPath retains only complete escapes when display expands", () => {
  const uri = "%EF%B8%8F".repeat(1100);
  assert.equal(decodeSarifUri(uri), "\ufe0f".repeat(1100));
  assert.equal(sarifDisplayPath(uri), "\\u{fe0f}".repeat(1016) + "… [252 bytes omitted]");
  const sampled = "%EF%B8%8F".repeat(2709) + "%E2%80%A6%20%5B873%20bytes%20omitted%5D";
  const marker = "… [5952 bytes omitted]";
  const display = "\\u{fe0f}".repeat(1016) + marker;
  const projected = sarifDisplayPath(sampled, display);
  assert.equal(projected.slice(-marker.length), marker);
  assert.equal(projected, display);
  assert.equal(sarifDisplayPath("literal%E2%80%A6%20%5B873%20bytes%20omitted%5D"), "literal… [873 bytes omitted]");
});
